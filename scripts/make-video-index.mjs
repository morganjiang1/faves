// Builds src/data/videos.ts from assets/videos/<city>/manifest.json so every clip is a
// bundled asset (Metro needs static require() calls). Run after adding or replacing clips:
//   node scripts/make-video-index.mjs
// manifest.json: { "<placeId>": { "video": "<placeId>.mp4", "poster": "<placeId>.jpg", "creator": "@handle", "sourceUrl": "https://...",
//   "views"?: 12345, "postedAt"?: "2026-10-01T12:00:00Z", "placeholder"?: true } }
// The app shows each clip as a Faves post: the handle as the poster's username, the play count and
// when it was posted. sourceUrl stays in the manifest for our records and is never bundled. Play
// counts and dates come from the manifest, or from the scraped post in data/raw/<city>/tiktok.json.
// scripts/clip_quality.py picks each clip's best frame (posterAt, where playback starts) and
// puts each spot's best clip first.
import { execFileSync } from "node:child_process";
import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "assets", "videos");
const exists = (p) => stat(p).then(() => true, () => false);

const rows = [];
let bytes = 0;
for (const city of (await readdir(dir).catch(() => [])).sort()) {
  const mf = join(dir, city, "manifest.json");
  if (!(await exists(mf))) continue;
  const manifest = JSON.parse(await readFile(mf, "utf8"));
  const rawPath = join(root, "data", "raw", city, "tiktok.json");
  const scraped = new Map(((await exists(rawPath)) ? JSON.parse(await readFile(rawPath, "utf8")) : []).map((x) => [String(x.id), x]));
  // A place's extra clips ("more": [{ video, poster, creator, views, postedAt }]) follow its first one.
  const entries = Object.entries(manifest).flatMap(([placeId, v]) => [[placeId, v, 0], ...(v.more ?? []).map((m, i) => [placeId, { ...m, creator: m.creator ?? v.creator }, i + 1])]);
  for (const [placeId, v, order] of entries) {
    const video = join(dir, city, v.video);
    if (!(await exists(video))) { console.warn(`missing ${city}/${v.video}, skipped`); continue; }
    bytes += (await stat(video)).size;
    const poster = v.poster && (await exists(join(dir, city, v.poster))) ? v.poster : null;
    let seconds = null;
    try { seconds = Math.round(Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", video]).toString().trim())); } catch { /* no ffprobe */ }
    const post = scraped.get(String(v.sourceUrl ?? "").match(/\/video\/(\d+)/)?.[1] ?? "");
    const plays = Number(v.views ?? v.plays ?? post?.views ?? NaN);
    const postedAt = v.postedAt ?? (post?.uploadedAtFormatted || null);
    rows.push({ city, placeId, order, video: v.video, poster, creator: v.creator ?? null, plays: Number.isFinite(plays) ? plays : null, postedAt, placeholder: Boolean(v.placeholder), seconds, startAt: Number(v.posterAt) || 0 });
  }
}

const clip = (r) => `{ city: ${JSON.stringify(r.city)}, video: require("../../assets/videos/${r.city}/${r.video}"), poster: ${r.poster ? `require("../../assets/videos/${r.city}/${r.poster}")` : "null"}, creator: ${JSON.stringify(r.creator)}, plays: ${r.plays ?? "null"}, postedAt: ${JSON.stringify(r.postedAt)}, placeholder: ${r.placeholder}, seconds: ${r.seconds ?? "null"}, startAt: ${r.startAt} }`;
const lines = rows.filter((r) => r.order === 0).map((r) => `  ${JSON.stringify(r.placeId)}: ${clip(r)},`);
const more = Object.entries(Object.groupBy(rows.filter((r) => r.order > 0), (r) => r.placeId)).map(([id, rs]) => `  ${JSON.stringify(id)}: [${rs.map(clip).join(", ")}],`);
const out = `// Generated by scripts/make-video-index.mjs from assets/videos/*/manifest.json. Do not edit.
// ${rows.length} clips, ${(bytes / 1024 / 1024).toFixed(1)} MB.
/* eslint-disable @typescript-eslint/no-require-imports */
export interface SpotClip { city: string; video: number; poster: number | null; creator: string | null; plays: number | null; postedAt: string | null; placeholder: boolean; seconds: number | null; startAt: number }

export const CLIPS: Record<string, SpotClip> = {
${lines.join("\n")}
};

// A place's extra clips, after its first one.
export const MORE_CLIPS: Record<string, SpotClip[]> = {
${more.join("\n")}
};
`;
await writeFile(join(root, "src", "data", "videos.ts"), out);
console.log(`src/data/videos.ts: ${rows.length} clips, ${(bytes / 1024 / 1024).toFixed(1)} MB`);
